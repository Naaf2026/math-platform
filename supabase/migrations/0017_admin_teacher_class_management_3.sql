-- Admin / Teacher Class Management 3.0
-- Stage A: secure role, class, roster and teacher-assignment foundation.
-- Idempotent migration: safe to run more than once.

create table if not exists public.user_roles (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  role text not null check (role in ('student','parent','guardian','teacher','admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists user_roles_role_idx on public.user_roles(role);

create table if not exists public.classes (
  id bigint generated by default as identity primary key,
  name text not null,
  class_code text not null unique,
  grade text,
  learning_level text,
  description text not null default '',
  created_by uuid not null references public.profiles(id) on delete restrict,
  status text not null default 'active' check (status in ('active','archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists classes_created_by_idx on public.classes(created_by);
create index if not exists classes_status_idx on public.classes(status);

create table if not exists public.class_members (
  id bigint generated by default as identity primary key,
  class_id bigint not null references public.classes(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'active' check (status in ('active','removed')),
  joined_at timestamptz not null default now(),
  unique(class_id, student_id)
);

create index if not exists class_members_class_idx on public.class_members(class_id,status);
create index if not exists class_members_student_idx on public.class_members(student_id,status);

create table if not exists public.class_teachers (
  id bigint generated by default as identity primary key,
  class_id bigint not null references public.classes(id) on delete cascade,
  teacher_id uuid not null references public.profiles(id) on delete cascade,
  role text not null default 'teacher' check (role in ('teacher','lead_teacher')),
  status text not null default 'active' check (status in ('active','removed')),
  assigned_at timestamptz not null default now(),
  unique(class_id, teacher_id)
);

create index if not exists class_teachers_class_idx on public.class_teachers(class_id,status);
create index if not exists class_teachers_teacher_idx on public.class_teachers(teacher_id,status);

-- ------------------------------------------------------------
-- Security helpers
-- ------------------------------------------------------------

create or replace function public.has_role(p_role text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
      from public.user_roles ur
     where ur.user_id = auth.uid()
       and ur.role = p_role
  );
$$;

create or replace function public.is_class_teacher(p_class_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
      from public.class_teachers ct
     where ct.class_id = p_class_id
       and ct.teacher_id = auth.uid()
       and ct.status = 'active'
  );
$$;

create or replace function public.is_class_student(p_class_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
      from public.class_members cm
     where cm.class_id = p_class_id
       and cm.student_id = auth.uid()
       and cm.status = 'active'
  );
$$;

revoke all on function public.has_role(text) from public, anon;
grant execute on function public.has_role(text) to authenticated;
revoke all on function public.is_class_teacher(bigint) from public, anon;
grant execute on function public.is_class_teacher(bigint) to authenticated;
revoke all on function public.is_class_student(bigint) from public, anon;
grant execute on function public.is_class_student(bigint) to authenticated;

