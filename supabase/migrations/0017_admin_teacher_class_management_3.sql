alter table public.user_roles enable row level security;
alter table public.classes enable row level security;
alter table public.class_members enable row level security;
alter table public.class_teachers enable row level security;

drop policy if exists user_roles_self on public.user_roles;
create policy user_roles_self on public.user_roles
for select to authenticated
using (auth.uid() = user_id or public.has_role('admin'));

drop policy if exists classes_select on public.classes;
create policy classes_select on public.classes
for select to authenticated
using (
  public.has_role('admin')
  or created_by = auth.uid()
  or public.is_class_teacher(id)
  or public.is_class_student(id)
);

drop policy if exists classes_insert on public.classes;
create policy classes_insert on public.classes
for insert to authenticated
with check (
  public.has_role('admin')
  or (public.has_role('teacher') and created_by = auth.uid())
);

drop policy if exists classes_update on public.classes;
create policy classes_update on public.classes
for update to authenticated
using (
  public.has_role('admin')
  or (public.has_role('teacher') and created_by = auth.uid())
)
with check (
  public.has_role('admin')
  or (public.has_role('teacher') and created_by = auth.uid())
);

drop policy if exists classes_delete on public.classes;
create policy classes_delete on public.classes
for delete to authenticated
using (public.has_role('admin'));

drop policy if exists class_members_select on public.class_members;
create policy class_members_select on public.class_members
for select to authenticated
using (
  public.has_role('admin')
  or public.is_class_teacher(class_id)
  or public.is_class_student(class_id)
);

drop policy if exists class_members_insert on public.class_members;
create policy class_members_insert on public.class_members
for insert to authenticated
with check (
  public.has_role('admin')
  or public.is_class_teacher(class_id)
);

drop policy if exists class_members_update on public.class_members;
create policy class_members_update on public.class_members
for update to authenticated
using (
  public.has_role('admin')
  or public.is_class_teacher(class_id)
)
with check (
  public.has_role('admin')
  or public.is_class_teacher(class_id)
);

drop policy if exists class_members_delete on public.class_members;
create policy class_members_delete on public.class_members
for delete to authenticated
using (public.has_role('admin') or public.is_class_teacher(class_id));

drop policy if exists class_teachers_select on public.class_teachers;
create policy class_teachers_select on public.class_teachers
for select to authenticated
using (
  public.has_role('admin')
  or teacher_id = auth.uid()
  or public.is_class_teacher(class_id)
);

drop policy if exists class_teachers_insert on public.class_teachers;
create policy class_teachers_insert on public.class_teachers
for insert to authenticated
with check (public.has_role('admin'));

drop policy if exists class_teachers_update on public.class_teachers;
create policy class_teachers_update on public.class_teachers
for update to authenticated
using (public.has_role('admin'))
with check (public.has_role('admin'));

drop policy if exists class_teachers_delete on public.class_teachers;
create policy class_teachers_delete on public.class_teachers
for delete to authenticated
using (public.has_role('admin'));

