create or replace function public.create_learning_class(
  p_name text,
  p_class_code text,
  p_grade text default null,
  p_learning_level text default null,
  p_description text default ''
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  new_id bigint;
begin
  if auth.uid() is null then raise exception 'Not authenticated'; end if;
  if not (public.has_role('admin') or public.has_role('teacher')) then
    raise exception 'Only admins and teachers can create classes';
  end if;

  insert into public.classes(name,class_code,grade,learning_level,description,created_by)
  values (
    trim(p_name),
    upper(trim(p_class_code)),
    nullif(trim(p_grade),''),
    nullif(trim(p_learning_level),''),
    coalesce(p_description,''),
    auth.uid()
  )
  returning id into new_id;

  -- A teacher who creates a class automatically becomes its lead teacher.
  if public.has_role('teacher') and not public.has_role('admin') then
    insert into public.class_teachers(class_id,teacher_id,role)
    values(new_id,auth.uid(),'lead_teacher')
    on conflict(class_id,teacher_id) do update set status='active',role='lead_teacher';
  end if;

  return new_id;
end;
$$;

create or replace function public.add_student_to_class(
  p_class_id bigint,
  p_student_id uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'Not authenticated'; end if;
  if not (public.has_role('admin') or public.is_class_teacher(p_class_id)) then
    raise exception 'Not authorized to manage this class';
  end if;
  if not exists (select 1 from public.profiles where id=p_student_id) then
    raise exception 'Student profile not found';
  end if;

  insert into public.class_members(class_id,student_id,status)
  values(p_class_id,p_student_id,'active')
  on conflict(class_id,student_id) do update set status='active';
end;
$$;

create or replace function public.remove_student_from_class(
  p_class_id bigint,
  p_student_id uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'Not authenticated'; end if;
  if not (public.has_role('admin') or public.is_class_teacher(p_class_id)) then
    raise exception 'Not authorized to manage this class';
  end if;

  update public.class_members
     set status='removed'
   where class_id=p_class_id and student_id=p_student_id;
end;
$$;

create or replace function public.assign_teacher_to_class(
  p_class_id bigint,
  p_teacher_id uuid,
  p_teacher_role text default 'teacher'
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'Not authenticated'; end if;
  if not public.has_role('admin') then
    raise exception 'Only admins can assign teachers';
  end if;
  if p_teacher_role not in ('teacher','lead_teacher') then
    raise exception 'Invalid teacher role';
  end if;
  if not exists (
    select 1 from public.user_roles
     where user_id=p_teacher_id and role='teacher'
  ) then
    raise exception 'User is not assigned the teacher role';
  end if;

  insert into public.class_teachers(class_id,teacher_id,role,status)
  values(p_class_id,p_teacher_id,p_teacher_role,'active')
  on conflict(class_id,teacher_id) do update
    set role=excluded.role,status='active';
end;
$$;

revoke all on function public.create_learning_class(text,text,text,text,text) from public, anon;
grant execute on function public.create_learning_class(text,text,text,text,text) to authenticated;
revoke all on function public.add_student_to_class(bigint,uuid) from public, anon;
grant execute on function public.add_student_to_class(bigint,uuid) to authenticated;
revoke all on function public.remove_student_from_class(bigint,uuid) from public, anon;
grant execute on function public.remove_student_from_class(bigint,uuid) to authenticated;
revoke all on function public.assign_teacher_to_class(bigint,uuid,text) from public, anon;
grant execute on function public.assign_teacher_to_class(bigint,uuid,text) to authenticated;

