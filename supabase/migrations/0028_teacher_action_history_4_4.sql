create or replace function public.log_teacher_intervention_event()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  actor uuid;
  event_name text;
  note_value text;
  action_value text;
  status_value text;
begin
  actor := auth.uid();
  if actor is null then
    actor := coalesce((to_jsonb(new)->>'created_by')::uuid, (to_jsonb(new)->>'teacher_id')::uuid);
  end if;

  if tg_op = 'INSERT' then
    event_name := 'created';
    note_value := coalesce(to_jsonb(new)->>'note', to_jsonb(new)->>'notes', '');
    action_value := coalesce(to_jsonb(new)->>'action', to_jsonb(new)->>'intervention_type', '');
    status_value := coalesce(to_jsonb(new)->>'status', 'open');
  elsif tg_op = 'UPDATE' then
    if coalesce(to_jsonb(old)->>'status', '') <> coalesce(to_jsonb(new)->>'status', '') then
      event_name := case when coalesce(to_jsonb(new)->>'status', '') = 'completed' then 'completed' else 'reopened' end;
      note_value := coalesce(to_jsonb(new)->>'note', to_jsonb(new)->>'notes', '');
      action_value := coalesce(to_jsonb(new)->>'action', to_jsonb(new)->>'intervention_type', '');
      status_value := coalesce(to_jsonb(new)->>'status', '');
    elsif coalesce(to_jsonb(old)->>'follow_up_status', '') <> coalesce(to_jsonb(new)->>'follow_up_status', '')
       or coalesce(to_jsonb(old)->>'follow_up_note', '') <> coalesce(to_jsonb(new)->>'follow_up_note', '')
       or coalesce(to_jsonb(old)->>'follow_up_due_at', '') <> coalesce(to_jsonb(new)->>'follow_up_due_at', '') then
      event_name := 'follow_up_updated';
      note_value := coalesce(to_jsonb(new)->>'follow_up_note', '');
      action_value := coalesce(to_jsonb(new)->>'action', to_jsonb(new)->>'intervention_type', '');
      status_value := coalesce(to_jsonb(new)->>'status', '');
    else
      return new;
    end if;
  else
    return new;
  end if;

  insert into public.teacher_intervention_events(intervention_id, actor_id, event_type, event_note, metadata)
  values (
    new.id,
    actor,
    event_name,
    note_value,
    jsonb_build_object(
      'action', action_value,
      'status', status_value,
      'follow_up_status', coalesce(to_jsonb(new)->>'follow_up_status', 'not_required'),
      'follow_up_due_at', to_jsonb(new)->>'follow_up_due_at'
    )
  );

  return new;
end;
$$;

