create trigger teacher_intervention_audit_trigger
after insert or update on public.teacher_interventions
for each row execute function public.log_teacher_intervention_event();

create or replace function public.get_teacher_action_history(
  p_class_id bigint default null,
  p_student_id uuid default null,
  p_status text default null,
  p_topic text default null,
  p_limit integer default 100
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  result jsonb;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  select coalesce(jsonb_agg(row_data order by created_at desc), '[]'::jsonb)
    into result
  from (
    select
      ti.created_at,
      jsonb_build_object(
        'id', ti.id,
        'class_id', ti.class_id,
        'class_name', c.name,
        'student_id', ti.student_id,
        'student_name', coalesce(nullif(p.display_name, ''), nullif(p.full_name, ''), 'Student'),
        'action', coalesce(to_jsonb(ti)->>'action', to_jsonb(ti)->>'intervention_type', 'review'),
        'topic_id', to_jsonb(ti)->>'topic_id',
        'note', coalesce(to_jsonb(ti)->>'note', to_jsonb(ti)->>'notes', ''),
        'status', ti.status,
        'created_at', ti.created_at,
        'completed_at', ti.completed_at,
        'follow_up_status', coalesce(ti.follow_up_status, 'not_required'),
        'follow_up_due_at', ti.follow_up_due_at,
        'follow_up_completed_at', ti.follow_up_completed_at,
        'follow_up_note', coalesce(ti.follow_up_note, ''),
        'events', coalesce((
          select jsonb_agg(jsonb_build_object(
            'id', e.id,
            'event_type', e.event_type,
            'event_note', e.event_note,
            'actor_id', e.actor_id,
            'created_at', e.created_at,
            'metadata', e.metadata
          ) order by e.created_at desc)
          from public.teacher_intervention_events e
          where e.intervention_id = ti.id
        ), '[]'::jsonb),
        'follow_up_activity_7d', (
          select count(*)::integer
          from public.question_attempts qa
          where qa.user_id = ti.student_id
            and ti.completed_at is not null
            and qa.created_at > ti.completed_at
            and qa.created_at <= ti.completed_at + interval '7 days'
        )
      ) as row_data
    from public.teacher_interventions ti
    join public.classes c on c.id = ti.class_id
    join public.profiles p on p.id = ti.student_id
    where (
      public.has_role('admin')
      or public.is_class_teacher(ti.class_id)
      or coalesce((to_jsonb(ti)->>'created_by')::uuid, (to_jsonb(ti)->>'teacher_id')::uuid) = auth.uid()
    )
      and (p_class_id is null or ti.class_id = p_class_id)
      and (p_student_id is null or ti.student_id = p_student_id)
      and (p_status is null or ti.status = p_status)
      and (p_topic is null or lower(coalesce(to_jsonb(ti)->>'topic_id', '')) like '%' || lower(trim(p_topic)) || '%')
    order by ti.created_at desc
    limit greatest(1, least(coalesce(p_limit, 100), 500))
  ) q;

  return result;
end;
$$;

create or replace function public.update_teacher_follow_up(
  p_intervention_id bigint,
  p_status text,
  p_due_at timestamptz default null,
  p_note text default ''
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  target_class bigint;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;
  if p_status not in ('not_required','pending','in_progress','completed') then
    raise exception 'Invalid follow-up status';
  end if;

  select class_id into target_class
  from public.teacher_interventions
  where id = p_intervention_id;

  if target_class is null or not (
    public.has_role('admin')
    or public.is_class_teacher(target_class)
  ) then
    raise exception 'Intervention not found or not authorized';
  end if;

  update public.teacher_interventions
     set follow_up_status = p_status,
         follow_up_due_at = case when p_status in ('pending','in_progress') then p_due_at else null end,
         follow_up_completed_at = case when p_status = 'completed' then coalesce(follow_up_completed_at, now()) else null end,
         follow_up_note = coalesce(trim(p_note), '')
   where id = p_intervention_id;
end;
$$;

